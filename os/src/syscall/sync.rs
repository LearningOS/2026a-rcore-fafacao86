/// enable deadlock detection syscall
pub fn sys_enable_deadlock_detect(enabled: usize) -> isize {
    trace!("kernel: sys_enable_deadlock_detect {}", enabled);
    match enabled {
        0 | 1 => {
            current_process()
                .inner_exclusive_access()
                .deadlock_detector
                .set_enabled(enabled == 1);
            0
        }
        _ => -1,
    }
}
